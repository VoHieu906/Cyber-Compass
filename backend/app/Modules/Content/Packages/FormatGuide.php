<?php

namespace App\Modules\Content\Packages;

use App\Models\Lesson;
use App\Models\Post;
use App\Modules\Content\Blocks\BlockRegistry;
use App\Modules\Content\Services\ContentFileMedia;

/**
 * Builds the AI authoring guide (D71) from its hand-written source and the registry: the limits
 * come from the configuration, and the block reference from every registered block type (its
 * description, whether it states facts, its JSON Schema and its first valid fixture). A new block
 * type with fixtures appears here with no change to this class. `content:format-guide` writes
 * the result; a test fails while the committed guide is out of date.
 */
final class FormatGuide
{
    public const DIR = 'content-format';

    public function __construct(private readonly BlockRegistry $blocks) {}

    public static function path(string $file): string
    {
        return resource_path(self::DIR.'/'.$file);
    }

    public function render(): string
    {
        $source = (string) file_get_contents(self::path('AI_AUTHORING_GUIDE.source.md'));
        $header = "<!-- Generated by `php artisan content:format-guide` from AI_AUTHORING_GUIDE.source.md and the block registry. Edit the source, then regenerate. -->\n\n";

        return $header.strtr($source, [
            '<!-- generated: limits -->' => $this->limits(),
            '<!-- generated: block-reference -->' => $this->blockReference(),
        ]);
    }

    private function limits(): string
    {
        $c = config('cybercompass.content_packages');
        $mb = fn (int $bytes) => intdiv($bytes, 1024 * 1024).' MB';

        return implode("\n", [
            '## 7. Limits',
            '',
            '| What | Limit |',
            '|---|---|',
            '| Sections in a lesson | '.Lesson::MAX_SECTIONS.' |',
            '| Sections in a blog post | '.Post::MAX_SECTIONS.' |',
            '| Sources per section | 8 |',
            '| Operations in one package | '.$c['max_operations'].' |',
            '| Lessons in one `course` bundle | '.$c['max_documents'].' |',
            '| One JSON document (the package, or a `.json` file in a bundle) | '.$mb($c['max_document_bytes']).' |',
            '| JSON nesting depth | '.$c['max_json_depth'].' |',
            '| One `$file` text | '.$mb($c['max_text_bytes']).' |',
            '| A zip bundle | '.$mb($c['max_bytes']).' compressed, '.$mb($c['max_uncompressed_bytes']).' unpacked, '.$c['max_entries'].' files |',
            '| Files allowed in a bundle | '.implode(', ', array_map(fn ($e) => ".{$e}", [...$c['text_extensions'], ...ContentFileMedia::EXTENSIONS])).' |',
            '',
            'Text fields have their own length limits, given in each block\'s schema below (`maxLength`, `maxItems`).',
        ]);
    }

    private function blockReference(): string
    {
        $out = ['## 10. Block reference', '', 'Every block type the platform accepts, generated from its registry. A payload must match its schema exactly; extra fields are refused. Each example is a complete section you can adapt.', ''];
        $out[] = '| Type | Name | States facts | Purpose |';
        $out[] = '|---|---|---|---|';
        foreach ($this->blocks->all() as $key => $block) {
            $out[] = "| `{$key}` | {$block->label()} | {$this->factualText($key)} | {$block->description()} |";
        }

        foreach ($this->blocks->all() as $key => $block) {
            $schema = (array) json_decode((string) json_encode($block->schema()), true);
            unset($schema['$schema'], $schema['examples'], $schema['x-factual']);
            $fixtures = json_decode((string) file_get_contents(app_path("Modules/Content/Blocks/fixtures/{$key}.valid.json")), true);
            $example = ['key' => "example-{$key}", 'type' => $key, 'heading' => $block->label(), 'payload' => $fixtures[0] ?? $block->example()];

            array_push($out, '',
                "### `{$key}`: {$block->label()}",
                '',
                $block->description().' **States facts:** '.$this->factualText($key).'.'.$this->factualNotes($key),
                '',
                'Schema:',
                '',
                '```json',
                self::json($schema),
                '```',
                '',
                'Example section:',
                '',
                '```json',
                self::json($example),
                '```',
            );
        }

        $sources = json_decode((string) file_get_contents(app_path('Modules/Content/Documents/schemas/sources.json')), true);
        unset($sources['$schema']);
        array_push($out, '', '### `sources` (on any section)', '', 'Schema:', '', '```json', self::json($sources), '```');

        return implode("\n", $out);
    }

    /** "yes: cite sources", "no", or the condition: "when `tone` is info, warning or fun-fact: cite sources". */
    private function factualText(string $type): string
    {
        $rule = $this->blocks->factualRule($type);
        if (is_bool($rule)) {
            return $rule ? 'yes: cite sources' : 'no';
        }
        $values = array_map(fn ($v) => (string) $v, (array) $rule->in);
        $list = count($values) > 1 ? implode(', ', array_slice($values, 0, -1)).' or '.end($values) : $values[0];

        return "when `{$rule->property}` is {$list}: cite sources";
    }

    private function factualNotes(string $type): string
    {
        $rule = $this->blocks->factualRule($type);
        $notes = is_bool($rule) ? [] : (array) ($rule->notes ?? []);

        return implode('', array_map(fn ($value, $note) => " For `{$value}`: {$note}", array_keys($notes), $notes));
    }

    private static function json(mixed $value): string
    {
        return json_encode($value, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }
}
